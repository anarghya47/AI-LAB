from itertools import product



def implies(P, Q):
    return (not P) or Q



def evaluate_kb(P, Q, R):
    return (
        implies(Q, P)
        and implies(P, not Q)
        and (Q or R)
    )



def evaluate_query(choice, P, Q, R):
    if choice == 1:
        return R
    elif choice == 2:
        return implies(R, P)
    elif choice == 3:
        return implies(Q, R)



def entails(choice):

    for P, Q, R in product([False, True], repeat=3):

        kb = evaluate_kb(P, Q, R)
        query = evaluate_query(choice, P, Q, R)


        if kb and not query:
            return False


    return True



def print_truth_table():
    print("TRUTH TABLE ENUMERATION\n")

    print("P Q R | Q->P P->!Q Q|R | KB")
    print("--------------------------------")

    for P, Q, R in product([False, True], repeat=3):

        first = implies(Q, P)
        second = implies(P, not Q)
        third = Q or R
        kb = evaluate_kb(P, Q, R)


        tf = lambda x: "T" if x else "F"

        print(
            f"{tf(P)} {tf(Q)} {tf(R)} |"
            f"   {tf(first)}    {tf(second)}    "
            f"{tf(third)} | {tf(kb)}"
        )



print_truth_table()

print("\nENTAILMENT RESULTS")

