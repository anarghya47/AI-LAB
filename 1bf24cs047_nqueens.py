import random
import time

def get_conflicts(state):
    """Calculate the number of conflicts (attacking pairs) on the board."""
    n = len(state)
    conflicts = 0
    for i in range(n):
        for j in range(i + 1, n):
            if state[i] == state[j]:
                conflicts += 1
            elif abs(state[i] - state[j]) == abs(i - j):
                conflicts += 1
    return conflicts

def get_best_neighbor(state):
    """Find the best neighbor by moving one queen in its column."""
    n = len(state)
    current_conflicts = get_conflicts(state)
    best_state = list(state)
    best_conflicts = current_conflicts
    neighbors = []

    for col in range(n):
        for row in range(n):
            if state[col] == row:
                continue
            neighbor = list(state)
            neighbor[col] = row
            conflicts = get_conflicts(neighbor)

            if conflicts < best_conflicts:
                best_conflicts = conflicts
                neighbors = [neighbor]
            elif conflicts == best_conflicts:
                neighbors.append(neighbor)

    if neighbors:
        return random.choice(neighbors), best_conflicts
    return state, current_conflicts

def print_board(state):
    """Helper to print the board layout nicely with its conflicts."""
    n = len(state)
    conflicts = get_conflicts(state)
    print(f"Current Board: {state} | Conflicts: {conflicts}")
    for row in range(n):
        line = ""
        for col in range(n):
            if state[col] == row:
                line += " Q "
            else:
                line += " . "
        print(line)
    print("-" * (n * 3))

def hill_climbing_with_steps(n):
    """Hill Climbing search showing each state change."""
    restarts = 0
    while True:
        print(f"\n=== Attempt {restarts + 1} ===")
        state = [random.randint(0, n - 1) for _ in range(n)]
        current_conflicts = get_conflicts(state)
        print_board(state)

        while True:
            neighbor, neighbor_conflicts = get_best_neighbor(state)
            if neighbor_conflicts >= current_conflicts:
                if neighbor_conflicts > 0:
                    print(f"Stuck in a local minimum with {neighbor_conflicts} conflicts. Restarting...\n")
                break
            state = neighbor
            current_conflicts = neighbor_conflicts
            print_board(state)

        if current_conflicts == 0:
            return state, restarts
        restarts += 1

